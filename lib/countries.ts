export const ARAB_FIRST: string[] = ["SA", "AE", "KW", "QA", "BH", "OM", "YE", "IQ", "JO", "SY", "LB", "PS", "EG", "SD", "LY", "TN", "DZ", "MA", "MR", "SO", "TR"];
const BY_CODE = new Map(COUNTRIES.map((c) => [c.code.toUpperCase(), c]));
/** اسم الدولة للعرض: الخادم يرسل الرمز، والقديم قد يكون اسماً */
export function countryName(v?: string | null): string {
  if (!v) return "";
  const c = BY_CODE.get(v.toUpperCase());
  return c ? c.ar : v;
}
export function countryFlag(v?: string | null): string {
  return (v && BY_CODE.get(v.toUpperCase())?.flag) || "";
}
